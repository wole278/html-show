let currentLang = localStorage.getItem('lkl_lang') || 'zh';

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('lkl_lang', lang);
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';

  const dict = I18N[lang];
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (dict[key].includes('<strong>')) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  document.getElementById('btnZh').classList.toggle('active', lang === 'zh');
  document.getElementById('btnEn').classList.toggle('active', lang === 'en');

  updateRouteMatcher();
}

function updateRouteMatcher() {
  const destEl = document.getElementById('matcherDest');
  const cargoEl = document.getElementById('matcherCargo');
  const resultBox = document.getElementById('matcherResult');
  if (!destEl || !cargoEl || !resultBox) return;

  const dest = destEl.value;
  const cargo = cargoEl.value;
  const rec =
    ROUTE_RECOMMENDATIONS[currentLang]?.[dest]?.[cargo] ||
    ROUTE_RECOMMENDATIONS[currentLang]['us-eu'].general;

  const badgeEl = resultBox.querySelector('.matcher-badge');
  const textEl = resultBox.querySelector('.matcher-text');
  if (badgeEl) badgeEl.textContent = rec.title;
  if (textEl) textEl.textContent = rec.desc;
}

